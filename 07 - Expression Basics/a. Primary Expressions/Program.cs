// Literal and simple name
int celsius = 18;
string city = "Bergen";

// Member access
Console.WriteLine(city.Length); // 6

// Invocation
Console.WriteLine(city.ToUpperInvariant()); // BERGEN

// Element access
Console.WriteLine(city[0]); // B

// Parenthesized expression
Console.WriteLine((celsius + 2) * 2); // 40
